"""Sinh js/data_bundle.js de web chay qua file:// (khong fetch duoc).

Khong bao gio sua tay file bundle. Chay lai sau khi doi du lieu processed:

    python src/make_bundle.py            # sinh bundle
    python src/make_bundle.py --check    # so hash bundle voi file nguon, exit 1 neu lech

File tuy chon (centrality.json, cluster_order.json, sensitivity.json) duoc dua
vao bundle neu ton tai; --check bao "stale" neu file moi xuat hien sau khi sinh.
"""
import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROCESSED = ROOT / "data" / "processed"
OUT = ROOT / "js" / "data_bundle.js"
MARKER = "window.DSDV_BUNDLE = "
HEADER = "// Generated by src/make_bundle.py - do not edit by hand.\n"

# name -> (bundle key, is_json, required)
SOURCES = {
    "network_data.json": ("network", True, True),
    "summary.csv": ("summary_csv", False, True),
    "centrality.json": ("centrality", True, False),
    "cluster_order.json": ("cluster_order", True, False),
    "sensitivity.json": ("sensitivity", True, False),
}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build() -> int:
    payload = {
        "generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "hashes": {},
    }
    for name, (key, is_json, required) in SOURCES.items():
        path = PROCESSED / name
        if not path.exists():
            if required:
                print(f"FAIL: missing required source {path}")
                return 1
            payload[key] = None
            continue
        payload["hashes"][name] = sha256(path)
        text = path.read_text(encoding="utf-8")
        payload[key] = json.loads(text) if is_json else text
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        HEADER + MARKER + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"OK: wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes, "
          f"{len(payload['hashes'])} sources)")
    return 0


def check() -> int:
    if not OUT.exists():
        print(f"FAIL: {OUT.relative_to(ROOT)} missing - run python src/make_bundle.py")
        return 1
    text = OUT.read_text(encoding="utf-8")
    start = text.find(MARKER)
    if start < 0:
        print("FAIL: bundle marker not found - regenerate")
        return 1
    try:
        payload = json.loads(text[start + len(MARKER):].rstrip().rstrip(";"))
    except json.JSONDecodeError as exc:
        print(f"FAIL: bundle is not valid JSON ({exc}) - regenerate")
        return 1
    ok = True
    for name, digest in payload.get("hashes", {}).items():
        path = PROCESSED / name
        if not path.exists():
            print(f"FAIL: {name} in bundle but source file is gone")
            ok = False
        elif sha256(path) != digest:
            print(f"FAIL: {name} changed since bundle was generated")
            ok = False
        else:
            print(f"ok: {name}")
    for name, (_, _, required) in SOURCES.items():
        if required or name in payload.get("hashes", {}):
            continue
        if (PROCESSED / name).exists():
            print(f"FAIL: {name} exists but is not in bundle (stale) - regenerate")
            ok = False
    print("OK: bundle matches sources" if ok else "FAIL: bundle stale - run python src/make_bundle.py")
    return 0 if ok else 1


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify bundle hashes instead of writing")
    args = parser.parse_args()
    sys.exit(check() if args.check else build())